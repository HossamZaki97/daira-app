"""Regenerate lib/design/icons.dart from the Phosphor web font package.

  npm pack @phosphor-icons/web && tar xzf phosphor-icons-web-*.tgz
  python tool/gen_icons.py package/src

Copy package/src/regular/Phosphor.ttf and package/src/fill/Phosphor-Fill.ttf to
assets/fonts/phosphor/ when upgrading. Add icons by editing ICONS below.
(The phosphor_flutter package no longer compiles: IconData is a final class.)"""
