def codes(style):
    css = open(f'{SRC}/{style}/style.css', encoding='utf-8').read()
    return {m.group(1): m.group(2) for m in re.finditer(r'\.ph(?:-fill)?\.ph-([a-z0-9-]+):before \{\s*content: "\\([0-9a-f]+)";', css)}


regular, fill = codes('regular'), codes('fill')
lines = []
for name, spec in ICONS.items():
    if spec is None:
        lines += ['', f'  {name}']
        continue
    icon, filled = spec
    code = (fill if filled else regular)[icon]
    family = 'PhosphorFill' if filled else 'Phosphor'
    lines.append(f"  static const {name} = IconData(0x{code}, fontFamily: '{family}'); // {icon}")

out = f'''// Generated by tool/gen_icons.py from the Phosphor icon font (MIT, assets/fonts/phosphor/LICENSE).
import 'package:flutter/widgets.dart';

/// The only icon set in the app (Phosphor, 24 grid, regular stroke; the
/// selected navigation item uses the fill variant). Use these names, never
/// Material icons, so the app and the backend stay consistent.
abstract final class AppIcons {{{chr(10).join(lines)}
}}

/// An icon that points "forward"/"back" in the reading direction.
class DirectionalIcon extends StatelessWidget {{
  const DirectionalIcon(this.icon, {{this.size, this.color, this.semanticLabel, super.key}});

  final IconData icon;
  final double? size;
  final Color? color;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {{
    final rtl = Directionality.of(context) == TextDirection.rtl;
    final child = Icon(icon, size: size, color: color, semanticLabel: semanticLabel);
    return rtl ? Transform.flip(flipX: true, child: child) : child;
  }}
}}
'''
open('lib/design/icons.dart', 'w', encoding='utf-8', newline='\n').write(out)
print('icons:', sum(1 for v in ICONS.values() if v))
